#!/usr/bin/env node
/**
 * Creates the Ed25519 key pair that signs licences and updates.
 *
 *   node scripts/keys.mjs            # only if no key exists yet
 *
 * - Private key → server/.secrets/ed25519-private.pem (NEVER commit, back it up:
 *   if it is lost, no existing licence or update can be verified again).
 * - Public key  → midi-script/Licensing/keys.py (shipped inside the script).
 */
import { generateKeyPairSync, createPrivateKey, createPublicKey } from "node:crypto";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const privPath = resolve(root, "server/.secrets/ed25519-private.pem");
const pyPath = resolve(root, "midi-script/Licensing/keys.py");

let privateKey;
if (existsSync(privPath)) {
  privateKey = createPrivateKey(readFileSync(privPath));
  console.log("• Ya existe una llave privada; solo se regenera keys.py");
} else {
  mkdirSync(dirname(privPath), { recursive: true });
  ({ privateKey } = generateKeyPairSync("ed25519"));
  writeFileSync(privPath, privateKey.export({ type: "pkcs8", format: "pem" }), { mode: 0o600 });
  console.log(`✓ Llave privada nueva: ${privPath}  (respáldala en un lugar seguro)`);
}
const raw = createPublicKey(privateKey).export({ type: "spki", format: "der" }).subarray(-32);
writeFileSync(
  pyPath,
  `# Generated by scripts/keys.mjs — public half of the DAW Remote signing key.\n` +
    `# Licences and updates are only accepted when signed by the matching private key.\n` +
    `PUBLIC_KEY_HEX = "${raw.toString("hex")}"\n`,
);
console.log(`✓ Llave pública → ${pyPath}`);
